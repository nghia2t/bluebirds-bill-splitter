// Apply hand-written migrations directly and register their hashes in
// drizzle.__drizzle_migrations so `pnpm db:migrate` will treat them as
// applied from now on.
//
// We do this instead of relying on `drizzle-kit migrate` because that tool
// silently skips migrations whose `meta/<idx>_snapshot.json` is missing —
// and our hand-written migrations don't have snapshots (the `generate`
// command can't produce one non-interactively).
//
// Usage:
//   pnpm exec node scripts/apply-running-ledger.mjs              # apply all hand-written migrations
//   pnpm exec node scripts/apply-running-ledger.mjs 0002...sql   # apply a specific one
//
// Each migration is idempotent — re-running it is a no-op once recorded.

import 'dotenv/config'
import { createHash } from 'node:crypto'
import { readFile, readdir } from 'node:fs/promises'
import { resolve } from 'node:path'
import postgres from 'postgres'

const url = process.env.NUXT_DATABASE_URL ?? process.env.DATABASE_URL
if (!url) {
  console.error('NUXT_DATABASE_URL is not set in .env')
  process.exit(1)
}

// The set of hand-written migrations we manage with this script.  Index 0000
// was generated by drizzle-kit and is applied via `pnpm db:migrate`.
const HAND_WRITTEN = new Set([
  '0001_running_ledger.sql',
  '0002_drop_vnd_input_mode.sql',
  '0003_bills_note.sql',
])

const wantFiles = process.argv.length > 2
  ? process.argv.slice(2)
  : (await readdir('server/db/migrations'))
      .filter((f) => HAND_WRITTEN.has(f))
      .sort()

const sql = postgres(url, { prepare: false, max: 1 })

try {
  for (const file of wantFiles) {
    await applyOne(file)
  }
} finally {
  await sql.end()
}

async function applyOne(file) {
  const migrationPath = resolve('server/db/migrations', file)
  const raw = await readFile(migrationPath, 'utf8')

  // Drizzle splits at "--> statement-breakpoint".  Each segment is its own
  // statement; empty segments (from a leading breakpoint) are dropped.
  const statements = raw
    .split('--> statement-breakpoint')
    .map((s) => s.trim())
    .filter((s) => s.length > 0)

  // Drizzle's own hash is sha256 over the raw file.  Matching it lets
  // `db:migrate` recognise the migration as already applied.
  const hash = createHash('sha256').update(raw).digest('hex')

  const already = await sql`
    SELECT 1 FROM drizzle.__drizzle_migrations WHERE hash = ${hash} LIMIT 1
  `
  if (already.length > 0) {
    console.log(`• ${file}: already applied (hash recorded), skipping.`)
    return
  }

  console.log(`▸ ${file}: applying ${statements.length} statement(s)…`)
  for (const [i, stmt] of statements.entries()) {
    const firstLine = stmt.split('\n').find((l) => !l.startsWith('--')) ?? stmt
    process.stdout.write(`  [${String(i + 1).padStart(2)}/${statements.length}] ${firstLine.slice(0, 80)}…`)
    try {
      await sql.unsafe(stmt)
      process.stdout.write(' ok\n')
    } catch (e) {
      process.stdout.write(' FAILED\n')
      throw e
    }
  }

  await sql`
    INSERT INTO drizzle.__drizzle_migrations (hash, created_at)
    VALUES (${hash}, ${Date.now()})
  `
  console.log(`✓ ${file}: applied and recorded.`)
  console.log(`  hash: ${hash}`)
}
